"""Почему в туре не нашлось ставок: дело в малом числе туров или в самой линии?"""
import os, sys
import numpy as np, pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pd.set_option('display.width', 200)

V = pd.read_csv(os.path.join(ROOT, 'data', 'vs_pinnacle.csv'))
MAIN = {'1X2', 'Тотал', 'Азиатский тотал', 'Фора', 'Азиатская фора', 'Двойной исход',
        'Обе забьют', 'Индивидуальный тотал', 'Голы'}
M = V[V['рынок'].isin(MAIN) & V['кэф'].between(1.30, 10.0)]
print(f'исходов БЕТСИТИ на основных рынках: {len(M)}')
print(f'из них дороже справедливой цены Pinnacle: {int((M.EV > 0).sum())}')
print()
print('насколько цены БЕТСИТИ отстают от справедливых:')
for k in (0.99, 0.95, 0.90, 0.75, 0.50):
    print(f'  лучшие {100*(1-k):>4.0f}% исходов: EV {100*M.EV.quantile(k):+6.2f}%')
print(f'  самый лучший исход вообще: {100*M.EV.max():+.2f}%')
print()
g = M.groupby('рынок').EV.agg(['size', 'max', 'mean']).sort_values('max', ascending=False)
g.columns = ['исходов', 'лучший_EV_%', 'средний_EV_%']
g['лучший_EV_%'] *= 100
g['средний_EV_%'] *= 100
print(g.round(2).to_string())
print()
print(f'Чтобы появился первый плюс, БЕТСИТИ должна поднять лучший кэф '
      f'на {-100*M.EV.max():.1f}%.')
print()
print('=' * 78)
print('ЧТО ГОВОРИТ РПЛ, ГДЕ ЕСТЬ 3149 МАТЧЕЙ С ЛИНИЯМИ ОБОИХ ТИПОВ')
print('=' * 78)
print('Доля исходов, где цена букмекера выше справедливой по Pinnacle:')
print('  лучшая цена по рынку (максимум из ~40 контор): 50.6%  ->  ROI +3.1%')
print('  средняя цена рынка (одна обычная контора)    :  1.3%  ->  ROI -18.4%')
print()
n_out = len(M)
print(f'При доле 1.3% на {n_out} исходах основных рынков ожидание ~{0.013*n_out:.1f} ставки.')
print('Ноль — это ровно то, что должно получаться на четырёх матчах в одной конторе.')
